"""Small, dependency-free Markdown renderer for the local report card.

The web UI runs from the standard library, so a full Markdown package is not
part of the base install.  Reports generated by kconv only use a small subset
of Markdown (headings, lists, tables, fenced/inline code, emphasis and links).
This renderer escapes every text fragment before adding its own tags, so raw
HTML from a report is never executed by the browser.
"""

from __future__ import annotations

import html
import re
from urllib.parse import urlsplit

_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
_UL_RE = re.compile(r"^\s*[-*+]\s+(.*)$")
_OL_RE = re.compile(r"^\s*\d+[.)]\s+(.*)$")
_FENCE_RE = re.compile(r"^\s*```")
_TABLE_SEPARATOR_CELL_RE = re.compile(r"^:?-{3,}:?$")
_LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
_ESCAPE_TOKEN = "\x00kconv-md-{}\x00"


def _emphasis(text: str) -> str:
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\w)__([^_]+)__(?!\w)", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\w)_([^_\n]+)_(?!\w)", r"<em>\1</em>", text)
    return re.sub(r"\*([^*\n]+)\*", r"<em>\1</em>", text)


def _safe_link(match: re.Match[str]) -> str:
    label, url = match.group(1), match.group(2)
    scheme = urlsplit(html.unescape(url)).scheme.lower()
    if scheme not in {"http", "https", "mailto"}:
        return match.group(0)
    href = html.escape(html.unescape(url), quote=True)
    return f'<a href="{href}" rel="noreferrer noopener" target="_blank">{_emphasis(label)}</a>'


def _protect_links(part: str) -> tuple[str, list[str]]:
    links: list[str] = []

    def keep_link(match: re.Match[str]) -> str:
        link = _safe_link(match)
        if link == match.group(0):
            return link
        token = _ESCAPE_TOKEN.format(len(links))
        links.append(link)
        return token

    return _LINK_RE.sub(keep_link, part), links


def _inline(text: str) -> str:
    """Escape text, protect code spans and links, then apply inline markup."""
    escaped = html.escape(text, quote=True)
    parts = re.split(r"(`[^`]*`)", escaped)
    rendered: list[str] = []
    for part in parts:
        if len(part) >= 2 and part.startswith("`") and part.endswith("`"):
            rendered.append(f"<code>{part[1:-1]}</code>")
            continue
        part, links = _protect_links(part)
        part = _emphasis(part)
        for position, link in enumerate(links):
            part = part.replace(_ESCAPE_TOKEN.format(position), link)
        rendered.append(part)
    return "".join(rendered)


def _cells(row: str) -> list[str]:
    value = row.strip()
    if value.startswith("|"):
        value = value[1:]
    if value.endswith("|"):
        value = value[:-1]
    return [cell.strip() for cell in value.split("|")]


def _is_table_separator(row: str) -> bool:
    if "|" not in row:
        return False
    cells = _cells(row)
    return bool(cells) and all(_TABLE_SEPARATOR_CELL_RE.fullmatch(cell) for cell in cells)


def _alignment(cell: str) -> str:
    left = cell.startswith(":")
    right = cell.endswith(":")
    if left and right:
        return "center"
    if right:
        return "right"
    if left:
        return "left"
    return ""


def _table(lines: list[str], start: int) -> tuple[str, int]:
    header = _cells(lines[start])
    separators = _cells(lines[start + 1])
    alignments = [_alignment(cell) for cell in separators]
    classes = [f' class="md-{alignment}"' if alignment else "" for alignment in alignments]
    classes.extend([""] * (len(header) - len(classes)))
    body_rows: list[str] = []
    index = start + 2
    while index < len(lines):
        line = lines[index]
        if not line.strip() or "|" not in line:
            break
        cells = _cells(line)
        cells += [""] * (len(header) - len(cells))
        rendered_cells = []
        for position, cell in enumerate(cells[: len(header)]):
            rendered_cells.append(f"<td{classes[position]}>{_inline(cell)}</td>")
        body_rows.append("<tr>" + "".join(rendered_cells) + "</tr>")
        index += 1
    head = "".join(
        f"<th{classes[position]}>{_inline(cell)}</th>" for position, cell in enumerate(header)
    )
    return (
        '<div class="md-table-wrap"><table><thead><tr>'
        + head
        + "</tr></thead><tbody>"
        + "".join(body_rows)
        + "</tbody></table></div>",
        index,
    )


def _render_block(lines: list[str], start: int) -> tuple[str, int]:
    line = lines[start]
    heading = _HEADING_RE.match(line)
    if heading:
        level = len(heading.group(1))
        return f"<h{level}>{_inline(heading.group(2))}</h{level}>", start + 1

    if re.fullmatch(r"\s*([-*_])(?:\s*\1){2,}\s*", line):
        return "<hr>", start + 1

    if _UL_RE.match(line) or _OL_RE.match(line):
        ordered = bool(_OL_RE.match(line))
        pattern = _OL_RE if ordered else _UL_RE
        items: list[str] = []
        index = start
        while index < len(lines):
            item = pattern.match(lines[index])
            if not item:
                break
            items.append(f"<li>{_inline(item.group(1))}</li>")
            index += 1
        tag = "ol" if ordered else "ul"
        return f"<{tag}>" + "".join(items) + f"</{tag}>", index

    if line.lstrip().startswith(">"):
        quote: list[str] = []
        index = start
        while index < len(lines) and lines[index].lstrip().startswith(">"):
            quote.append(lines[index].lstrip()[1:].lstrip())
            index += 1
        return "<blockquote><p>" + _inline(" ".join(quote)) + "</p></blockquote>", index

    if "|" in line and start + 1 < len(lines) and _is_table_separator(lines[start + 1]):
        return _table(lines, start)

    paragraph: list[str] = []
    index = start
    while index < len(lines) and lines[index].strip():
        if index > start and (
            _HEADING_RE.match(lines[index])
            or _UL_RE.match(lines[index])
            or _OL_RE.match(lines[index])
            or lines[index].lstrip().startswith(">")
            or (index + 1 < len(lines) and _is_table_separator(lines[index + 1]))
        ):
            break
        paragraph.append(lines[index].strip())
        index += 1
    return "<p>" + _inline(" ".join(paragraph)) + "</p>", index


def render_markdown(text: str | None) -> str:
    """Render the report subset into safe HTML.

    The output intentionally has no raw-HTML passthrough.  Unknown Markdown
    constructs are shown as escaped text rather than being dropped.
    """
    if not text:
        return ""
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    output: list[str] = []
    index = 0
    while index < len(lines):
        if not lines[index].strip():
            index += 1
            continue
        if _FENCE_RE.match(lines[index]):
            index += 1
            code: list[str] = []
            while index < len(lines) and not _FENCE_RE.match(lines[index]):
                code.append(lines[index])
                index += 1
            if index < len(lines):
                index += 1
            output.append("<pre><code>" + html.escape("\n".join(code), quote=False) + "</code></pre>")
            continue
        block, index = _render_block(lines, index)
        output.append(block)
    return "\n".join(output)
