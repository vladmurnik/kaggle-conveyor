"""Cross-validation splitters used by the validate stage and tests."""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq
from sklearn.model_selection import (
    GroupKFold,
    KFold,
    StratifiedKFold,
    TimeSeriesSplit,
    train_test_split,
)

from kconv.config import Config
from kconv.contracts import Fold
from kconv.errors import DataError


def _classification(task: str) -> bool:
    return task in {"binary", "multiclass"}


def choose_strategy(config: Config, y: np.ndarray, *, task: str | None = None) -> str:
    """Resolve ``auto`` into a concrete splitter name.

    ``config.task`` may still be ``auto`` in a hand-written config.  Callers
    that already ran ingest should pass the detected ``task`` so a binary
    target gets stratified folds even when the config was not generated by
    ``build_config``.
    """
    effective_task = task or config.task
    requested = config.validation.strategy
    if requested != "auto":
        return requested
    if config.validation.group_col:
        return "group_kfold"
    if config.validation.time_col:
        return "time_series"
    if _classification(effective_task):
        return "stratified_kfold"
    return "kfold"


def _safe_stratified_splits(y: np.ndarray, requested: int) -> int:
    counts = pd.Series(y).value_counts(dropna=False)
    if len(counts) < 2:
        raise DataError(
            "Stratified CV needs at least two target classes.",
            "Use --task regression or check the target column.",
        )
    minimum = int(counts.min())
    if minimum < 2:
        raise DataError(
            "Stratified CV needs at least two rows per class.",
            "Use fewer folds, collect more data, or switch to kfold.",
        )
    return max(2, min(int(requested), minimum))


def build_folds(
    config: Config,
    y: np.ndarray,
    *,
    groups: np.ndarray | None = None,
    time: np.ndarray | None = None,
    task: str | None = None,
) -> list[Fold]:
    """Build deterministic folds with positional integer indices."""
    y = np.asarray(y)
    n_rows = len(y)
    if n_rows < 4:
        raise DataError(
            f"Need at least 4 labeled rows for CV, got {n_rows}.",
            "Add more training rows or use a simple holdout with more data.",
        )
    effective_task = task or config.task
    strategy = choose_strategy(config, y, task=effective_task)
    requested = int(config.validation.n_splits)
    shuffle = bool(config.validation.shuffle)
    seed = int(config.validation.random_state)

    if strategy == "holdout":
        stratify = y if _classification(effective_task) and pd.Series(y).value_counts().min() >= 2 else None
        train_idx, valid_idx = train_test_split(
            np.arange(n_rows),
            test_size=config.validation.holdout_size,
            random_state=seed,
            shuffle=True,
            stratify=stratify,
        )
        return [Fold(index=0, train_idx=np.asarray(train_idx, dtype=np.int64), valid_idx=np.asarray(valid_idx, dtype=np.int64))]

    if strategy == "stratified_kfold":
        splits = _safe_stratified_splits(y, requested)
        splitter = StratifiedKFold(n_splits=splits, shuffle=shuffle, random_state=seed)
        iterator = splitter.split(np.zeros(n_rows), y)
    elif strategy == "kfold":
        splits = max(2, min(requested, n_rows))
        splitter = KFold(n_splits=splits, shuffle=shuffle, random_state=seed)
        iterator = splitter.split(np.zeros(n_rows))
    elif strategy == "group_kfold":
        if groups is None:
            raise DataError(
                "group_kfold requires a group column.",
                "Set validation.group_col to a column that exists in train.",
            )
        groups = np.asarray(groups)
        if pd.isna(groups).any():
            raise DataError(
                "Group column contains missing values; group splits would be ambiguous.",
                "Fill or drop missing groups before running CV.",
            )
        unique_groups = pd.unique(groups)
        if len(unique_groups) < 2:
            raise DataError(
                "group_kfold needs at least two distinct groups in the train split.",
                "Collect more groups or switch to another validation strategy.",
            )
        splits = max(2, min(requested, len(unique_groups)))
        splitter = GroupKFold(n_splits=splits)
        iterator = splitter.split(np.zeros(n_rows), y, groups=groups)
    elif strategy == "time_series":
        if time is None:
            raise DataError(
                "time_series CV requires a time column.",
                "Set validation.time_col to a sortable datetime/numeric column.",
            )
        order = np.argsort(np.asarray(time), kind="stable")
        # TimeSeriesSplit returns indices into the supplied array; use ordered
        # data so the returned positions map back to original row positions.
        splits = max(2, min(requested, max(2, n_rows - 1)))
        splitter = TimeSeriesSplit(n_splits=splits, gap=int(config.validation.gap))
        try:
            raw_splits = list(splitter.split(np.arange(n_rows)))
        except ValueError as exc:
            raise DataError(
                f"time_series CV could not be built: {exc}",
                "Reduce validation.gap or validation.n_splits.",
            ) from exc
        iterator = (
            (np.asarray(order[train], dtype=np.int64), np.asarray(order[valid], dtype=np.int64))
            for train, valid in raw_splits
        )
    else:
        raise DataError(
            f"Unknown validation strategy '{strategy}'.",
            "Use auto|kfold|stratified_kfold|group_kfold|time_series|holdout.",
        )

    folds: list[Fold] = []
    for index, (train_idx, valid_idx) in enumerate(iterator):
        train_idx = np.asarray(train_idx, dtype=np.int64)
        valid_idx = np.asarray(valid_idx, dtype=np.int64)
        if len(valid_idx) == 0 or len(train_idx) == 0:
            raise DataError("A generated fold is empty.", "Use fewer folds or more data.")
        folds.append(Fold(index=index, train_idx=train_idx, valid_idx=valid_idx))
    if not folds:
        raise DataError("CV produced no folds.", "Check validation settings.")
    return folds


def _atomic_write_bytes(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass


def _atomic_write_text(path: Path, payload: str) -> None:
    _atomic_write_bytes(path, payload.encode("utf-8"))


def _validate_train_indices(
    train: Any,
    valid: Any,
    n_rows: int,
    fold_id: Any,
) -> None:
    """Fail closed when a fold artifact could leak validation rows into train."""
    train_array = np.asarray(train, dtype=np.int64)
    valid_array = np.asarray(valid, dtype=np.int64)
    if train_array.ndim != 1 or valid_array.ndim != 1:
        raise DataError(
            f"Fold {fold_id} has a non-1D train or validation index array.",
            "Rerun the validate stage; this artifact is corrupted.",
        )
    if train_array.size and (train_array.min() < 0 or train_array.max() >= n_rows):
        raise DataError(
            f"Fold {fold_id} train indices are outside [0, {n_rows}).",
            "Rerun the validate stage; this artifact is corrupted.",
        )
    if valid_array.size and (valid_array.min() < 0 or valid_array.max() >= n_rows):
        raise DataError(
            f"Fold {fold_id} validation indices are outside [0, {n_rows}).",
            "Rerun the validate stage; this artifact is corrupted.",
        )
    if len(np.unique(train_array)) != len(train_array):
        raise DataError(
            f"Fold {fold_id} contains duplicate train rows.",
            "Rerun the validate stage; this artifact is corrupted.",
        )
    if len(np.unique(valid_array)) != len(valid_array):
        raise DataError(
            f"Fold {fold_id} contains duplicate validation rows.",
            "Rerun the validate stage; this artifact is corrupted.",
        )
    if np.intersect1d(train_array, valid_array, assume_unique=False).size:
        raise DataError(
            f"Fold {fold_id} train and validation rows overlap.",
            "Rerun the validate stage; overlapping rows would leak the target.",
        )


def save_folds(folds: list[Fold], path: str | Path, n_rows: int) -> None:
    records: list[dict[str, int]] = []
    seen = np.zeros(n_rows, dtype=bool)
    for fold in folds:
        _validate_train_indices(fold.train_idx, fold.valid_idx, n_rows, fold.index)
        for row_id in fold.valid_idx:
            row_id = int(row_id)
            if row_id < 0 or row_id >= n_rows:
                raise DataError(f"Fold contains out-of-range row {row_id}.", "This is a bug in the splitter.")
            if seen[row_id]:
                raise DataError(f"Row {row_id} appears in more than one fold.", "This is a bug in the splitter.")
            seen[row_id] = True
            records.append({"row_id": row_id, "fold": int(fold.index)})
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    frame = pd.DataFrame(records)
    # Persist the universe size so holdout/time-series folds can reconstruct
    # train indices even when the highest validation id is not n_rows - 1.
    frame["n_rows"] = int(n_rows)
    # Keep the exact train membership in the same Parquet file.  Writing the
    # Parquet file and a separate JSON sidecar is not atomic: a crash between
    # the two writes used to leave a file whose missing sidecar made
    # time-series folds fall back to "everything except validation", leaking
    # future rows into the training side.
    train_membership = {str(fold.index): [int(i) for i in fold.train_idx] for fold in folds}
    metadata = {b"kconv_folds_train": json.dumps(train_membership, separators=(",", ":")).encode("utf-8")}
    table = pa.Table.from_pandas(frame, preserve_index=False)
    table = table.replace_schema_metadata({**(table.schema.metadata or {}), **metadata})
    buffer = pa.BufferOutputStream()
    pq.write_table(table, buffer)
    _atomic_write_bytes(path, buffer.getvalue().to_pybytes())
    # Keep the sidecar for older readers and for human inspection.  New
    # readers prefer the metadata embedded in the Parquet file.
    _atomic_write_text(path.with_name("folds_train.json"), json.dumps(train_membership))


def _fold_membership(path: Path, table: pa.Table) -> dict[str, list[int]]:
    membership: dict[str, list[int]] = {}
    raw_metadata = table.schema.metadata or {}
    raw = raw_metadata.get(b"kconv_folds_train")
    if raw:
        try:
            parsed = json.loads(raw.decode("utf-8"))
            if isinstance(parsed, dict):
                membership = parsed
        except (UnicodeDecodeError, json.JSONDecodeError):
            membership = {}
    sidecar = path.with_name("folds_train.json")
    if sidecar.exists():
        try:
            parsed = json.loads(sidecar.read_text(encoding="utf-8"))
            if isinstance(parsed, dict):
                # Prefer the embedded copy when both exist; the sidecar is
                # only a compatibility fallback.
                membership = membership or parsed
        except (OSError, json.JSONDecodeError):
            pass
    return membership


def load_folds(path: str | Path, *, strategy: str | None = None) -> list[Fold]:
    path = Path(path)
    table = pq.read_table(path)
    frame = table.to_pandas()
    if not {"row_id", "fold"}.issubset(frame.columns):
        raise DataError(
            f"Fold file {path} must contain columns row_id and fold.",
            "Rerun the validate stage; this artifact is corrupted.",
        )
    folds: list[Fold] = []
    all_ids = frame["row_id"].to_numpy(dtype=np.int64)
    n_rows = int(frame["n_rows"].iloc[0]) if "n_rows" in frame.columns else int(all_ids.max()) + 1
    universe = np.arange(n_rows, dtype=np.int64)
    train_membership = _fold_membership(path, table)
    if not train_membership and strategy == "time_series":
        raise DataError(
            "Time-series folds are missing their exact training membership.",
            "Rerun the validate stage; falling back to 'all except validation' would leak future rows.",
        )
    for fold_id, group in frame.groupby("fold", sort=True):
        valid = group["row_id"].to_numpy(dtype=np.int64)
        if str(fold_id) in train_membership:
            train = np.asarray(train_membership[str(fold_id)], dtype=np.int64)
        else:
            train = np.setdiff1d(universe, valid, assume_unique=False)
        _validate_train_indices(train, valid, n_rows, fold_id)
        folds.append(Fold(index=int(fold_id), train_idx=train, valid_idx=valid))
    return folds


def load_run_folds(run_dir: str | Path) -> list[Fold]:
    """Load folds with the strategy persisted by the validate stage."""
    run_dir = Path(run_dir)
    summary_path = run_dir / "01_validate" / "cv_summary.json"
    strategy: str | None = None
    if summary_path.exists():
        try:
            summary = json.loads(summary_path.read_text(encoding="utf-8"))
            if isinstance(summary, dict):
                strategy = str(summary.get("strategy") or "") or None
        except (OSError, json.JSONDecodeError):
            strategy = None
    return load_folds(run_dir / "01_validate" / "folds.parquet", strategy=strategy)
